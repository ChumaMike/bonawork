// Bundles database/migrations/*.sql into database/migrations/bundle.ts so the
// app can apply migrations at startup without reading the file system — the
// same code path works for Postgres, PGlite, tests and serverless bundles.
// Run by `pnpm db:generate` after `drizzle-kit generate`.
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const folder = join(dirname(fileURLToPath(import.meta.url)), "migrations");
const journal = JSON.parse(readFileSync(join(folder, "meta", "_journal.json"), "utf8"));

const entries = journal.entries.map((entry) => {
  const sqlText = readFileSync(join(folder, `${entry.tag}.sql`), "utf8");
  return {
    tag: entry.tag,
    when: entry.when,
    hash: createHash("sha256").update(sqlText).digest("hex"),
    statements: sqlText.split("--> statement-breakpoint").map((s) => s.trim()),
  };
});

const out = `// GENERATED by database/bundle-migrations.mjs — do not edit.
// Source: the .sql files next to this file (drizzle-kit generate).
export interface BundledMigration {
  tag: string;
  when: number;
  hash: string;
  statements: string[];
}

export const migrations: BundledMigration[] = ${JSON.stringify(entries, null, 2)};
`;

writeFileSync(join(folder, "bundle.ts"), out);
console.log(`bundled ${entries.length} migration(s) into database/migrations/bundle.ts`);
