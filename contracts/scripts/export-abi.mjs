// Writes the committed ABI files consumed by the web app and the verifier.
// Run via `pnpm abi` (compiles first).
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";

const artifact = JSON.parse(
  readFileSync(
    new URL("../artifacts/contracts/BonaRegistry.sol/BonaRegistry.json", import.meta.url),
    "utf8",
  ),
);
const abiJson = JSON.stringify(artifact.abi, null, 2);
const outDir = new URL("../abi/", import.meta.url);
mkdirSync(outDir, { recursive: true });

// Plain JSON: for ethers, other languages and block explorers.
writeFileSync(new URL("BonaRegistry.json", outDir), `${abiJson}\n`);

// `as const` module: gives viem/wagmi/abitype full type inference.
writeFileSync(
  new URL("BonaRegistry.ts", outDir),
  `// Generated by scripts/export-abi.mjs — do not edit by hand.\nexport const bonaRegistryAbi = ${abiJson} as const;\n`,
);

console.log(`Exported ${artifact.abi.length} ABI entries to contracts/abi/`);
