// Writes the committed ABI files of the Bona Chain suite, consumed by the web app and the
// verifier:  contracts/abi/chain/{factory,operations,finance}.{ts,json}
// Run via `pnpm chain:abi` (compiles first).
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";

const CONTRACTS = [
  { file: "factory", contract: "BonaChainFactory", exportName: "bonaChainFactoryAbi" },
  {
    file: "operations",
    contract: "InstitutionOperations",
    exportName: "institutionOperationsAbi",
  },
  { file: "finance", contract: "InstitutionFinance", exportName: "institutionFinanceAbi" },
];

const outDir = new URL("../../abi/chain/", import.meta.url);
mkdirSync(outDir, { recursive: true });

for (const { file, contract, exportName } of CONTRACTS) {
  const artifact = JSON.parse(
    readFileSync(
      new URL(
        `../../artifacts/contracts/chain/${contract}.sol/${contract}.json`,
        import.meta.url,
      ),
      "utf8",
    ),
  );
  const abiJson = JSON.stringify(artifact.abi, null, 2);

  // Plain JSON: for ethers, other languages and block explorers.
  writeFileSync(new URL(`${file}.json`, outDir), `${abiJson}\n`);

  // `as const` module: gives viem/wagmi/abitype full type inference.
  writeFileSync(
    new URL(`${file}.ts`, outDir),
    `// Generated by scripts/chain/export-abi.mjs from ${contract}.sol — do not edit by hand.\nexport const ${exportName} = ${abiJson} as const;\n`,
  );
  console.log(
    `Exported ${artifact.abi.length} ABI entries of ${contract} to contracts/abi/chain/${file}.{ts,json}`,
  );
}
